// SSE 线上格式：把一个宿主事件编成 `text/event-stream` 的一帧。
// ---------------------------------------------------------------------------
// 只做一件事：**文本 → 线上字节**。谁来订阅、什么时候写、连接怎么关，全在
// `eventsRouteStream.ts`；载荷长什么样是 C2 的账。本文件因此可以脱离 socket 单测，
// 而「换行怎么处理」这类只在字符串层面成立的性质，也只有在这里才能被逐字节钉住。
//
// ═══ 帧的形状 ═══
//
//     event: mcp-stdio-close⏎
//     data: {"serverId":"a","sessionToken":"b","message":"…"}⏎
//     ⏎
//
// 三段：`event:` 给事件名、`data:` 给载荷、**空行结束一帧**。行分隔符统一用 `\n`
// （规范允许 CRLF / CR / LF 三种，收端必须三种都认，发端没有理由挑最啰嗦的那个）。
//
// ═══ 【核心】`data` 里含换行怎么办 ═══
//
// SSE 是**按行**解析的协议：`data:` 字段可以出现多次，收端把每次的值用 `\n` 拼回来。
// 所以一段含换行的正文**必须**拆成多条 `data:` 行；直接把带裸换行的字符串写进一条 `data:`，
// 换行之后那部分会被收端当成新的一行来解析——轻则字段名不认识而被丢弃，重则那一行恰好是
// `⏎⏎` 就提前结束了本帧，后面的内容变成下一帧的开头。
//
// 今天 `JSON.stringify(payload)`（**不传第三个参数**）的输出里不可能有裸换行：字符串内容里的
// U+000A / U+000D 被转义成 `\n` / `\r` 两个字符，而不传 `space` 就不会缩进换行。也就是说本函数
// 里的拆行分支目前**恒不发生**。
//
// **但拆行不是可省的**，理由有二，都不是假设：
//   1. 那个前提是别人一行代码就能推翻的。给 `JSON.stringify` 加个 `null, 2` 让日志好看一点，
//      是极自然的一次改动，而它的后果是线上帧从第二行起全部错位——**不报错**，收端只是
//      「有时收不到事件」。把拆行做成结构上成立的事，这条改动就只是让帧变长，不是让它坏掉。
//   2. `data` 的内容**来自 MCP 子进程**（close 事件的 `message` 是子进程/传输给出的原因文本，
//      多行是常态）。虽然 JSON 转义已经把它挡住，但「安全性依赖上一层恰好做了转义」和
//      「本层自己就不可能被注入」是两回事，而后者才配写进一个协议编码器。
// 拆行分支不能只靠注释活着——`eventsRouteFrame.test.ts` 直接喂多行文本走这条分支，
// 并连同「正文里塞一整帧」的注入尝试一起钉住。
//
// ═══ 刻意不发的两个字段：`id:` 与 `retry:` ═══
//
// 两个都只对 `EventSource` 的内建重连有意义，而本端点的客户端**不是** `EventSource`
// （理由见 `eventsRoute.ts` 的文件头：设不了 `Authorization` 头）。
//   · `id:` 会让收端记住 `Last-Event-ID` 并在重连时带回来——而我们不做重放（理由同上，
//     写在 `eventsRoute.ts`）。发一个自己不打算兑现的续传锚点，比不发更坏。
//   · `retry:` 是给内建重连调间隔的旋钮，退避策略在客户端手里。
//
// ═══ 事件名为什么不需要转义 ═══
//
// `name` 的类型是 C2 的收敛联合 `HostEventName`，取值只可能是 `HOST_EVENT_NAMES` 里那两个
// 字面量，不含冒号也不含换行。这不是「我们检查过」，是类型上就构造不出别的值——所以这里
// 没有、也不该有一个「事件名要不要转义」的运行期分支。真要加第三个事件名，得先回
// `hostEventNames.ts` 登记，那一步会被看见。

import type { HostEventName } from '@einfach-agent/host-node'

/**
 * `charset=utf-8` 是冗余的（SSE 规范固定 UTF-8 解码），写出来是为了和 `httpReply.ts` 里
 * 每一条 content-type 保持同一个书写口径；浏览器按参数无关的方式匹配 MIME 类型。
 */
export const EVENT_STREAM_CONTENT_TYPE = 'text/event-stream; charset=utf-8'

/** 规范认这三种行分隔符。发端只产 `\n`，收端三种都得认。 */
const SSE_LINE_BREAK = /\r\n|\r|\n/

/**
 * 编一帧事件。`data` 收的是**已经序列化好的文本**而不是对象——这样「换行怎么拆」这条性质
 * 才能被直接喂进来测（对象经 `JSON.stringify` 出来永远不含裸换行，测不到那条分支）。
 */
export function encodeSseFrame(name: HostEventName, data: string): string {
  const lines = [`event: ${name}`]
  // 空串 `''.split(...)` 得到 `['']`，于是仍产出一条 `data: ` 空行——收端拼回来还是空串。
  for (const segment of data.split(SSE_LINE_BREAK)) lines.push(`data: ${segment}`)
  // 末尾的空行是帧边界：`join` 出的最后一行后面接 `\n\n` 正好是「行尾 + 一个空行」。
  return `${lines.join('\n')}\n\n`
}

/**
 * 编一条注释行（`:` 开头）。规范要求收端**忽略**它，所以它是「往连接上写点东西但不构成事件」
 * 的唯一合法手段——心跳与握手提示都走这条路，不可能被误解析成事件。
 *
 * 同样按行拆：注释正文里若混进换行，第二行就不再是注释而是被当作字段行解析，
 * 一句 `event: …` 就能凭空造出一帧。今天的调用点只传常量，但编码器的正确性不该建立在
 * 「调用点目前只传常量」上。
 *
 * **末尾不补空行**：空行会触发一次派发，规范随即因为 data 缓冲为空而把它丢掉——一个纯粹的
 * 空操作。少写两个字节，也少一处让读者以为「注释也算一帧」的暗示。
 */
export function encodeSseComment(text: string): string {
  return `${text.split(SSE_LINE_BREAK).map((segment) => `: ${segment}`).join('\n')}\n`
}
